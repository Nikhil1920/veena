    static func text(for language: Language?, url: URL = VeenaLinks.website) -> String {
        let english: String
        if let language {
            english = "I use Veena to turn my \(language.name) speech into text, offline on my phone. "
                + "It works in 22 Indian languages and it's open source."
        } else {
            english = "I use Veena to turn speech into text, offline on my phone. "
                + "It works in 22 Indian languages and it's open source."
        }
        let pitch = language.flatMap { pitches[$0.code] }
        return [pitch, english, url.absoluteString].compactMap { $0 }.joined(separator: "\n\n")
    }
